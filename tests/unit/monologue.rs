#[test]
fn multibyte_unicode_scalar_and_whitespace() {
    let mut text = String::from("A🧪B\u{2003}Привет");
    reverse_words_at_odd_positions(&mut text);
    assert_eq!(text, "B🧪A\u{2003}Привет");
}

#[test]
fn tabs_and_newlines_remain_unchanged() {
    let mut text = String::from("A🧪B\tПривет\nмир");
    reverse_words_at_odd_positions(&mut text);
    assert_eq!(text, "B🧪A\tПривет\nрим");
}

#[test]
fn combining_mark_is_reversed_as_a_separate_scalar_value() {
    let mut text = String::from("a\u{301}b c");
    reverse_words_at_odd_positions(&mut text);
    assert_eq!(text, "b\u{301}a c");
}
